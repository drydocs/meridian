import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const WASM_DIR = join(
  ROOT,
  "packages",
  "contracts",
  "target",
  "wasm32v1-none",
  "release"
);
const OUT_DIR = join(ROOT, "packages", "sdk", "src", "generated");

const CONTRACTS = [
  { wasm: "meridian_vault.wasm", out: "vault.ts" },
  { wasm: "meridian_musdc_token.wasm", out: "musdc.ts" },
  { wasm: "meridian_blend_adapter.wasm", out: "blend-adapter.ts" },
  { wasm: "meridian_defindex_adapter.wasm", out: "defindex-adapter.ts" },
] as const;

function main(): void {
  for (const { wasm } of CONTRACTS) {
    const wasmPath = join(WASM_DIR, wasm);
    if (!existsSync(wasmPath)) {
      console.error(
        `Missing built WASM: ${wasmPath}\n` +
          `Build the contracts first:\n` +
          `  cd packages/contracts && cargo build --target wasm32v1-none --release`
      );
      process.exit(1);
    }
  }

  mkdirSync(OUT_DIR, { recursive: true });
  const scratch = mkdtempSync(join(tmpdir(), "meridian-bindings-"));

  try {
    for (const { wasm, out } of CONTRACTS) {
      const wasmPath = join(WASM_DIR, wasm);
      const targetDir = join(scratch, out.replace(/\.ts$/, ""));

      execFileSync(
        "stellar",
        [
          "contract",
          "bindings",
          "typescript",
          "--wasm",
          wasmPath,
          "--output-dir",
          targetDir,
          "--overwrite",
        ],
        { stdio: "inherit" }
      );

      const generated = readFileSync(join(targetDir, "src", "index.ts"), "utf8")
        .replace(/\r\n/g, "\n")
        .replace(/\n*$/, "\n");

      const header =
        "// Auto-generated by `pnpm generate:bindings` via `stellar contract bindings typescript`.\n" +
        "// Do not edit by hand. Regenerate after any contract spec change.\n" +
        "/* eslint-disable */\n" +
        "// @ts-nocheck\n";

      writeFileSync(join(OUT_DIR, out), header + generated, "utf8");
      console.log(`Wrote packages/sdk/src/generated/${out}`);
    }
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

main();
